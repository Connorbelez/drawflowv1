export type QaCleanupTableName = (typeof QA_CLEANUP_TABLES)[number];

/**
 * WorkOS projection tables and the brokerage root are read-only to product
 * cleanup. WorkOS Management API changes and webhook convergence own these
 * records.
 */
export const QA_PROTECTED_TABLES = [
  "brokerages",
  "users",
  "workosOrganizations",
  "workosOrganizationMemberships",
  "workosOrganizationRoles",
  "workosRoles",
  "workosPermissions",
  "workosWebhookReceipts",
] as const satisfies readonly QaCleanupTableName[];

export function isQaCleanupTableName(
  value: string
): value is QaCleanupTableName {
  return (QA_CLEANUP_TABLES as readonly string[]).includes(value);
}

export function isQaProtectedTableName(
  value: string
): value is (typeof QA_PROTECTED_TABLES)[number] {
  return (QA_PROTECTED_TABLES as readonly string[]).includes(value);
}
